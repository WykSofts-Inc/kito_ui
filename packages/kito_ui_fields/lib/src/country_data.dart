// Calling-region metadata: ISO code, dial code, English name, national number masks (`#` is a
// digit), allowed lengths, trunk prefix, an example number, and leading digits that pick the
// region when several share a dial code.

part of 'country.dart';

KitoFieldCountry _c(String iso, String dial, String name, List<String> formats,
        {int? min,
        int? max,
        String? trunk,
        String? example,
        List<String> leading = const [],
        bool main = true}) =>
    KitoFieldCountry(
      isoCode: iso,
      dialCode: dial,
      englishName: name,
      formats: formats,
      minLength: min,
      maxLength: max,
      trunkPrefix: trunk,
      exampleNumber: example,
      leadingDigits: leading,
      isMainCountryForDialCode: main,
    );

